//! Heads-up postflop solver based on Discounted CFR.
//!
//! The solver works on the full range-vs-range game: every node stores, for
//! the acting player, one regret and one strategy accumulator per
//! `(action, hand)`. A single recursive pass handles all hands at once by
//! propagating the opponent's reach vector down the tree and returning the
//! traverser's counterfactual values (see [`cfr`]).
//!
//! Design notes (informed by b-inary/postflop-solver):
//! * DCFR (α = 1.5, β = 0, γ = 2) with alternating updates;
//! * O(n) showdown evaluation via strength-sorted sweeps with
//!   inclusion–exclusion card removal;
//! * the bet tree is generated by [`holdem::menu`], the same code the table
//!   uses, so every action played at the table exists in the tree;
//! * optional stratified sampling of turn/river cards for fast approximate
//!   flop solves.

