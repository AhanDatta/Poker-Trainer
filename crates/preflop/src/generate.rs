//! Making a chart file from scratch: solve a game with the model and write
//! its strategies as the trainer's charts (the `solve-preflop` command).

use crate::charts::{round_charts, solved_charts, MIN_MIX};
use crate::realize::Realization;
use crate::solver::{Diagnosis, Options, Solver};
use crate::spec::GameSpec;
use crate::tree::Tree;
use std::time::Instant;
use trainer::preflop::ChartSet;

/// Hand classes that reach a spot fewer times than this use the trainer's
/// fallback rules there.
pub const MIN_SAMPLES: u64 = 200;

/// Calls of [`Solver::run`] per solve (progress is reported after each).
pub const EPOCHS: u32 = 20;

/// Deals used to measure the finished solve.
pub const DIAGNOSIS_DEALS: u64 = 2_000_000;

/// What to solve.
#[derive(Clone, Debug)]
pub struct Job {
    pub spec: GameSpec,
    pub factors: Realization,
    /// Where the factors come from, for the file's header.
    pub factors_name: String,
    pub deals: u64,
    pub threads: usize,
    pub seed: u64,
}

/// Progress after one epoch.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Progress {
    pub epoch: u32,
    pub deals: u64,
    pub seconds: f64,
}

/// A finished solve.
#[derive(Debug)]
pub struct Output {
    /// Only the spots where some hand class was solved (the trainer's
    /// fallback rules cover the rest), in whole percents without mixes
    /// below [`MIN_MIX`].
    pub charts: ChartSet,
    pub diagnosis: Diagnosis,
    pub decisions: usize,
    pub seconds: f64,
}

/// Builds the tree of `job.spec`, solves it and turns it into charts.
/// `progress` is called after every epoch. Errors if the spec can't be
/// solved (bad settings, or a tree beyond the node limit).
pub fn solve(job: &Job, mut progress: impl FnMut(&Progress)) -> Result<Output, String> {
    let start = Instant::now();
    let tree = Tree::build(&job.spec).map_err(|e| e.to_string())?;
    let decisions = tree.num_decisions;
    let options = Options { threads: job.threads.max(1), seed: job.seed, ..Options::default() };
    let mut solver = Solver::new(tree, job.factors.clone(), options);
    for epoch in 1..=EPOCHS {
        let done = job.deals * (epoch - 1) as u64 / EPOCHS as u64;
        let next = job.deals * epoch as u64 / EPOCHS as u64;
        solver.run(next - done);
        progress(&Progress { epoch, deals: solver.deals(), seconds: start.elapsed().as_secs_f64() });
    }
    let diagnosis = solver.diagnose(DIAGNOSIS_DEALS, job.seed ^ 0x5eed);
    let mut charts = solved_charts(&solver, MIN_SAMPLES);
    round_charts(&mut charts, MIN_MIX);
    Ok(Output { charts, diagnosis, decisions, seconds: start.elapsed().as_secs_f64() })
}

/// The header of a generated chart file: the settings, factors and seed,
/// and how converged the solve is.
pub fn header(job: &Job, out: &Output) -> String {
    let s = &job.spec;
    let positions = holdem::game::positions(s.players);
    let mut lines = vec![
        format!("Generated by `poker-trainer solve-preflop` ({} decisions).", out.decisions),
        format!(
            "{} players, {}bb stacks, rake {}% capped at {}bb, at most {} cold caller(s) per raise.",
            s.players,
            s.stack_bb,
            s.rake_rate * 100.0,
            s.rake_cap_bb,
            if s.rules.max_cold_callers == usize::MAX { "any".to_string() } else { s.rules.max_cold_callers.to_string() }
        ),
        format!("Realization factors: {}.", job.factors_name),
        format!("Frequencies in whole percents; mixes below {:.0}% are dropped as sampling noise.", MIN_MIX * 100.0),
        format!(
            "{:.0} million deals, seed {}, {:.0} s. Hands that reach a spot fewer than {MIN_SAMPLES} times, and spots not in the file, use the fallback rules.",
            job.deals as f64 / 1e6,
            job.seed,
            out.seconds
        ),
        format!("Per position: result, then the gain from changing one decision (bb/100, on {:.0}M fresh deals):", out.diagnosis.deals as f64 / 1e6),
    ];
    for name in &positions {
        let seat = holdem::game::position_offset(s.players, name).expect("a position of the table");
        lines.push(format!(
            "  {name:<6} {:>7.1} {:>6.2}",
            100.0 * out.diagnosis.ev[seat],
            100.0 * out.diagnosis.deviation_gain[seat]
        ));
    }
    lines.join("\n")
}

